export function downloadTextFile(filename: string, content: string, mimeType = 'text/plain;charset=utf-8'): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export interface ASExportParams {
  symbol: string;
  gamma: number;
  kappa: number;
  sigmaBps: number;
  orderSize: number;
  hawkesThreshold: number;
  vpinThreshold: number;
}

export function generateAvellanedaStoikovPython(p: ASExportParams): string {
  return `"""
Market Microstructure Lab (MML) - Auto-Generated Strategy Export
Strategy: Avellaneda-Stoikov (2008) Optimal Market Making with Hawkes/VPIN Toxicity Kill-Switch
Target Symbol: ${p.symbol}
Generated UTC: ${new Date().toISOString()}
"""

import math
from dataclasses import dataclass

@dataclass
class ASConfig:
    symbol: str = "${p.symbol}"
    risk_aversion_gamma: float = ${p.gamma.toFixed(4)}
    order_book_liquidity_kappa: float = ${p.kappa.toFixed(2)}
    volatility_bps: float = ${p.sigmaBps.toFixed(2)}
    base_order_size: float = ${p.orderSize}
    hawkes_rho_limit: float = ${p.hawkesThreshold.toFixed(2)}
    vpin_toxicity_limit: float = ${p.vpinThreshold.toFixed(2)}

def compute_as_quotes(
    mid_price: float,
    inventory_q: float,
    time_remaining_frac: float,
    cfg: ASConfig,
    hawkes_rho: float = 0.0,
    live_vpin: float = 0.0
):
    """
    Computes reservation price r(s, q, t) and optimal bid/ask quotes.
    Automatically pulls resting quotes if supercritical Hawkes or toxic VPIN regime triggers.
    """
    if hawkes_rho >= cfg.hawkes_rho_limit or live_vpin >= cfg.vpin_toxicity_limit:
        return {"action": "PULL_QUOTES", "reason": "TOXICITY_KILL_SWITCH"}

    sigma_price = mid_price * (cfg.volatility_bps / 10000.0)
    gamma = cfg.risk_aversion_gamma
    kappa = cfg.order_book_liquidity_kappa
    tau = max(0.05, time_remaining_frac)

    # Reservation price: skews away from accumulated inventory
    reservation_price = mid_price - inventory_q * gamma * (sigma_price ** 2) * tau

    # Optimal total spread
    optimal_spread = gamma * (sigma_price ** 2) * tau + (2.0 / gamma) * math.log(1.0 + gamma / kappa)
    half_spread = optimal_spread / 2.0

    return {
        "action": "QUOTE",
        "reservation_price": round(reservation_price, 2),
        "bid_price": round(reservation_price - half_spread, 2),
        "ask_price": round(reservation_price + half_spread, 2),
        "half_spread_bps": round((half_spread / mid_price) * 10000.0, 3),
    }

if __name__ == "__main__":
    cfg = ASConfig()
    print("Sample Quote (q = +0.5 inventory skew):", compute_as_quotes(60000.0, 0.5, 0.8, cfg))
`;
}

export interface MicroAlphaExportParams {
  wOfi: number;
  wMpi: number;
  wCvd: number;
  wHawkes: number;
  horizonK: number;
  thresholdScore: number;
  ic: number;
  winRatePct: number;
  netBps: number;
}

export function generateMicroAlphaPython(p: MicroAlphaExportParams): string {
  return `"""
Market Microstructure Lab (MML) - Auto-Generated Micro-Alpha Signal Export
Calibrated Horizon: k = ${p.horizonK} ticks | Empirical IC = ${p.ic.toFixed(4)} | Win Rate = ${p.winRatePct.toFixed(1)}%
Generated UTC: ${new Date().toISOString()}
"""

import polars as pl

WEIGHTS = {
    "w_ofi": ${p.wOfi.toFixed(2)},
    "w_mpi": ${p.wMpi.toFixed(2)},
    "w_cvd": ${p.wCvd.toFixed(2)},
    "w_hawkes": ${p.wHawkes.toFixed(2)},
}
SIGNAL_THRESHOLD = ${p.thresholdScore.toFixed(2)}
HORIZON_K = ${p.horizonK}

def compute_composite_alpha(df: pl.DataFrame) -> pl.DataFrame:
    """
    Expects standardized z-score columns: ofi_z, mpi_z, cvd_z, hawkes_z.
    Returns directional signal (-1, 0, +1) with zero lookahead leakage.
    """
    w_sum = sum(abs(v) for v in WEIGHTS.values()) or 1.0
    return df.with_columns([
        (
            (
                WEIGHTS["w_ofi"] * pl.col("ofi_z")
                + WEIGHTS["w_mpi"] * pl.col("mpi_z")
                + WEIGHTS["w_cvd"] * pl.col("cvd_z")
                + WEIGHTS["w_hawkes"] * pl.col("hawkes_z")
            ) / w_sum
        ).alias("alpha_score")
    ]).with_columns([
        pl.when(pl.col("alpha_score") > SIGNAL_THRESHOLD).then(1)
        .when(pl.col("alpha_score") < -SIGNAL_THRESHOLD).then(-1)
        .otherwise(0)
        .alias("signal")
    ])
`;
}

export function generateResearchMemoMarkdown(title: string, sections: Array<{ heading: string; body: string }>): string {
  const header = `# ${title}\n\n> Generated by **Market Microstructure Lab (MML)** at \`${new Date().toISOString()}\`\n\n---\n\n`;
  const content = sections.map((s) => `## ${s.heading}\n\n${s.body}\n`).join('\n');
  return header + content;
}

export function exportRecordsToCsv(filename: string, rows: Array<Record<string, any>>): void {
  if (!rows || rows.length === 0) return;
  const headers = Object.keys(rows[0]);
  const csvLines = [
    headers.join(','),
    ...rows.map((r) =>
      headers
        .map((h) => {
          const val = r[h] ?? '';
          const str = String(val).replace(/"/g, '""');
          return str.includes(',') || str.includes('"') || str.includes('\n') ? `"${str}"` : str;
        })
        .join(',')
    )
  ];
  downloadTextFile(filename, csvLines.join('\n'), 'text/csv;charset=utf-8');
}
